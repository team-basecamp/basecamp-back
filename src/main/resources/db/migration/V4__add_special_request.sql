-- -------------------------------------------------------------
-- 1. reservations : 고객 요청사항 컬럼 추가
--    예약 시 고객이 남기는 자유 텍스트 요청.
--    (예: 늦은 체크인, 반려동물 동반, 인접 자리 배정, 조용한 구역 요청 등)
--
--    · 필수값이 아니므로 NULL 허용 (요청사항 없이 예약 가능).
--    · 자유 서술형이지만 무한정 길어질 필요는 없어 VARCHAR(500) 으로 제한.
--      더 긴 서술이 필요하면 TEXT 로 변경 가능.
--    · MySQL 에서 컬럼 물리 순서는 기능상 의미가 없어 AFTER 는 생략.
--      특정 위치에 두고 싶으면 `AFTER <컬럼명>` 을 붙일 것.
-- -------------------------------------------------------------
ALTER TABLE reservations
    ADD COLUMN special_request VARCHAR(500) NULL
        COMMENT '고객 요청사항 (예약 시 자유 입력, 선택)';